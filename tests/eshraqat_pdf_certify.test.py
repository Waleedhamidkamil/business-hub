# -*- coding: utf-8 -*-
"""Eshraqat PDFs: metadata scrub + invisible certification, never AES (2026-10-17).

Waleed asked that Eshraqat documents not read as generated by the same tool as
Abraj's. Instead of the AES-256 lock, an Eshraqat PDF is:
  - stripped of the `/Info` entries that name the renderer (Chrome's
    `/Creator`, `/Producer`), and
  - sealed with an INVISIBLE certification signature from his own certificate.

`pdf_lock.lock` is the single final-protection step all four generators call, so
the profile split is pinned there: Abraj still AES-encrypts; Eshraqat routes to
`pdf_certify.finish_eshraqat` and is never encrypted.

These tests use a throwaway certificate generated in-process and a monkeypatched
`sign_settings`, so nothing here touches the live secrets.json or the real .pfx.
"""
from __future__ import annotations

import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from backend import pdf_certify, pdf_lock  # noqa: E402


def _make_pfx(passphrase: bytes) -> Path:
    import datetime
    from cryptography import x509
    from cryptography.x509.oid import NameOID
    from cryptography.hazmat.primitives import hashes
    from cryptography.hazmat.primitives.asymmetric import rsa
    from cryptography.hazmat.primitives.serialization import (
        pkcs12, BestAvailableEncryption)
    key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    name = x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, "Test Signer")])
    now = datetime.datetime.now(datetime.timezone.utc)
    cert = (x509.CertificateBuilder().subject_name(name).issuer_name(name)
            .public_key(key.public_key()).serial_number(x509.random_serial_number())
            .not_valid_before(now - datetime.timedelta(days=1))
            .not_valid_after(now + datetime.timedelta(days=3650))
            .sign(key, hashes.SHA256()))
    blob = pkcs12.serialize_key_and_certificates(
        b"t", key, cert, None, BestAvailableEncryption(passphrase))
    fd, name_s = tempfile.mkstemp(suffix=".pfx")
    import os
    os.close(fd)
    Path(name_s).write_bytes(blob)
    return Path(name_s)


def _chrome_pdf() -> Path:
    from pypdf import PdfWriter
    w = PdfWriter()
    w.add_blank_page(width=595, height=842)
    w.add_metadata({"/Creator": "Mozilla/5.0 HeadlessChrome/155",
                    "/Producer": "Skia/PDF m155", "/Title": "QT-9999"})
    fd, name = tempfile.mkstemp(suffix=".pdf")
    import os
    os.close(fd)
    with open(name, "wb") as fh:
        w.write(fh)
    return Path(name)


def _is_encrypted(path: Path) -> bool:
    from pypdf import PdfReader
    return bool(PdfReader(str(path)).is_encrypted)


def _sig_count(path: Path) -> int:
    from pyhanko.pdf_utils.reader import PdfFileReader
    with open(path, "rb") as fh:
        return len(PdfFileReader(fh).embedded_signatures)


def _meta(path: Path) -> dict:
    from pypdf import PdfReader
    r = PdfReader(str(path))
    if r.is_encrypted:
        r.decrypt("")
    return dict(r.metadata or {})


class EshraqatCertify(unittest.TestCase):

    @classmethod
    def setUpClass(cls):
        cls.pfx = _make_pfx(b"pw-123")

    @classmethod
    def tearDownClass(cls):
        cls.pfx.unlink(missing_ok=True)

    def setUp(self):
        self._profile = pdf_lock_config().ACTIVE_PROFILE
        self._settings = pdf_certify.sign_settings
        pdf_certify.sign_settings = lambda: {
            "enabled": True, "pfx_path": str(self.pfx), "passphrase": "pw-123"}

    def tearDown(self):
        pdf_lock_config().ACTIVE_PROFILE = self._profile
        pdf_certify.sign_settings = self._settings

    def test_scrub_blanks_renderer_fields_keeps_title(self):
        pdf = _chrome_pdf()
        try:
            pdf_certify.scrub_metadata(pdf)
            m = _meta(pdf)
            self.assertEqual(m.get("/Creator"), "")
            self.assertEqual(m.get("/Producer"), "")
            self.assertEqual(m.get("/Title"), "QT-9999", "the number is kept")
        finally:
            pdf.unlink(missing_ok=True)

    def test_finish_certifies_and_leaves_no_fingerprint(self):
        pdf = _chrome_pdf()
        try:
            pdf_certify.finish_eshraqat(pdf)
            self.assertFalse(_is_encrypted(pdf), "Eshraqat is never AES-locked")
            self.assertEqual(_sig_count(pdf), 1, "one certification signature")
            raw = pdf.read_bytes()
            for tell in (b"Skia", b"HeadlessChrome", b"pyHanko", b"Mozilla"):
                self.assertNotIn(tell, raw, f"{tell!r} must not survive")
        finally:
            pdf.unlink(missing_ok=True)

    def test_lock_routes_eshraqat_to_certify_not_aes(self):
        pdf_lock_config().ACTIVE_PROFILE = "eshraqat"
        pdf = _chrome_pdf()
        try:
            pdf_lock.lock(pdf)
            self.assertFalse(_is_encrypted(pdf))
            self.assertEqual(_sig_count(pdf), 1)
        finally:
            pdf.unlink(missing_ok=True)

    def test_lock_still_aes_encrypts_abraj(self):
        pdf_lock_config().ACTIVE_PROFILE = "abraj"
        pdf = _chrome_pdf()
        try:
            pdf_lock.lock(pdf)
            self.assertTrue(_is_encrypted(pdf), "Abraj keeps AES-256")
            self.assertEqual(_sig_count(pdf), 0, "Abraj is not certified")
        finally:
            pdf.unlink(missing_ok=True)


def pdf_lock_config():
    from backend import config
    return config


if __name__ == "__main__":
    unittest.main(verbosity=2)
