# -*- coding: utf-8 -*-
"""Eshraqat PDFs carry no verification mark (Waleed, 2026-10-17).

The "Verification: <no> | <code>" line is printed on every Abraj document and
logged to `doc_verify_log`. Waleed asked that Eshraqat documents show nothing of
the sort: its PDFs must not read as generated by the same tool, and nothing may
tie one Eshraqat file to another or to this machine.

`doc_verify.stamp_pdf` is the single choke point (all four generators call it),
so the gate lives there. These tests pin both sides: Abraj still stamps and
logs; Eshraqat does neither. The gate reads `config.ACTIVE_PROFILE` at call time,
so the profile is set per-case here and the test does not depend on the registry.
"""
from __future__ import annotations

import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from backend import doc_verify  # noqa: E402


def _blank_pdf() -> Path:
    from pypdf import PdfWriter
    w = PdfWriter()
    w.add_blank_page(width=595, height=842)
    fd, name = tempfile.mkstemp(suffix=".pdf")
    import os
    os.close(fd)
    with open(name, "wb") as fh:
        w.write(fh)
    return Path(name)


def _text(path: Path) -> str:
    from pypdf import PdfReader
    r = PdfReader(str(path))
    if r.is_encrypted:
        r.decrypt("")
    return "".join(p.extract_text() or "" for p in r.pages)


def _logged(no: str) -> bool:
    conn = doc_verify._connect()
    try:
        row = conn.execute(
            "SELECT 1 FROM doc_verify_log WHERE doc_no = ?", (no,)).fetchone()
        return row is not None
    finally:
        conn.close()


class EshraqatNoVerification(unittest.TestCase):

    def setUp(self):
        self._profile = doc_verify.config.ACTIVE_PROFILE

    def tearDown(self):
        doc_verify.config.ACTIVE_PROFILE = self._profile

    def _doc(self, no):
        return {"quote_no": no, "date": "17/10/2026", "client_name": "ZZTEST",
                "currency": "USD", "items": [{"qty": "1", "rate": "10"}]}

    def test_abraj_stamps_and_logs(self):
        doc_verify.config.ACTIVE_PROFILE = "abraj"
        no = "ZZ-VERIFY-ABRAJ"
        pdf = _blank_pdf()
        try:
            doc_verify.stamp_pdf(pdf, "qut", self._doc(no))
            self.assertIn("Verification", _text(pdf),
                          "Abraj must keep its verification line")
            self.assertTrue(_logged(no), "Abraj must log the code")
        finally:
            pdf.unlink(missing_ok=True)

    def test_eshraqat_stamps_nothing(self):
        doc_verify.config.ACTIVE_PROFILE = "eshraqat"
        no = "ZZ-VERIFY-ESHRAQAT"
        pdf = _blank_pdf()
        try:
            out = doc_verify.stamp_pdf(pdf, "qut", self._doc(no))
            self.assertEqual(out, pdf, "the path is returned unchanged")
            self.assertNotIn("Verification", _text(pdf),
                             "Eshraqat must carry no verification line")
            self.assertFalse(_logged(no),
                             "Eshraqat must not log a code - nothing ties its files together")
        finally:
            pdf.unlink(missing_ok=True)


if __name__ == "__main__":
    unittest.main(verbosity=2)
